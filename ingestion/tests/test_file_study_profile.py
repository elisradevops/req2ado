"""The file study's document profile (prompt study_file_rules_document v4): what the model says about a document beyond its grammar -- its
kind, its cover title, wrapper proposals, heading spelling fixes and the title policy -- each part checked against the document on its own
(a part that fails is dropped, never the answer), voted by strict majority, kept in the rulebook (an older rulebook keeps its hash), and the
user's decisions on the proposals stored beside them.

Owner decisions (2026-11-25): dropping or renaming a wrapper is a proposal the user decides, the file's original is kept until then; a
spelling fix is applied automatically, so it must be small; a proposed name is grounded in the section's own sub-headings or the cover."""

