@cache
def _load(path: str):
    return load_pdf(path)


def _i(headings: list[dict], number: str) -> int:
    return next(h["i"] for h in headings if h["number"] == number)


def _j(lines: list[dict], text: str) -> int:
    return next(line["j"] for line in lines if line["text"].startswith(text))


def _answer(**parts) -> dict:
    return {
        "type_source": "none",
        "labels": [],
        "depth_types": [],
        "evidence_headings": [],
        "front_matter_headings": [],
        "requirement_codes": [
            "gen_2",
            "enc_1",
            "mec_3",
        ],  # a valid grammar, so each test checks only its own part
        "leaf_convention": "unknown",
        "empty_sections": "unknown",
        "context_headings": [],
        "back_matter_headings": [],
        "document_kind": "unknown",
        "cover_title_lines": [],
        "proposals": [],
        "spelling_fixes": [],
        "title_policy": "unknown",
        **parts,
    }


def _rules(twin, **parts) -> DocumentRules:
    headings = document_headings(twin)
    rules = validate_document_answer(_answer(**parts), headings, twin, cover=cover_lines(twin))
    assert isinstance(rules, DocumentRules), rules
    return rules


# --- what the model is shown ------------------------------------------------------------------------------------------------------------


def test_the_sample_shows_the_cover_lines_of_the_whole_document(twin) -> None:
    lines = cover_lines(twin)
    texts = [line["text"] for line in lines]
    assert any(t.startswith("[412.7] Greenhouse Climate Controller") for t in texts)
    assert "COMPANY CONFIDENTIAL" in texts and not any(
        t.startswith("1.1 ") or t.startswith("REQUIREMENTS") for t in texts
    )
    assert [line["j"] for line in lines] == list(range(len(lines)))
    assert document_sample(twin, cover=lines)["coverLines"] == lines


# --- each part is checked against the document on its own -------------------------------------------------------------------------------


def test_the_document_kind_and_title_policy_are_closed_vocabularies(twin) -> None:
    rules = _rules(twin, document_kind="requirements_export", title_policy="write")
    assert rules.document_kind == "requirements_export" and rules.title_policy == "write"
    rules = _rules(twin, document_kind="novel", title_policy="poetic")
    assert rules.document_kind is None and rules.title_policy is None


def test_the_cover_title_is_the_lines_the_model_picked_joined_by_code(twin) -> None:
    lines = cover_lines(twin)
    rules = _rules(twin, cover_title_lines=[_j(lines, "[412.7] Greenhouse")])
    assert rules.cover_title == "[412.7] Greenhouse Climate Controller (GCC)"


@pytest.mark.parametrize(
    "picked",
    [
        ["COMPANY CONFIDENTIAL"],  # a marking, never a title
        ["The content of this specification"],  # the notice paragraph
        ["[412.7] Greenhouse", "Generated by PlantBase"],  # lines far apart are not one title
    ],
)
def test_a_cover_title_from_a_marking_a_notice_or_scattered_lines_is_refused(
    twin, picked: list[str]
) -> None:
    lines = cover_lines(twin)
    assert _rules(twin, cover_title_lines=[_j(lines, p) for p in picked]).cover_title is None
    assert _rules(twin, cover_title_lines=[999]).cover_title is None


def test_a_wrapper_proposal_is_checked_against_the_headings(twin) -> None:
    headings = document_headings(twin)
    ids = {h["i"]: h["block_id"] for h in headings}
    lines = cover_lines(twin)
    rules = _rules(
        twin,
        cover_title_lines=[_j(lines, "[412.7] Greenhouse")],
        proposals=[
            {
                "i": _i(headings, "2"),
                "action": "rename",
                "new_title": "Greenhouse Climate Controller (GCC)",
                "reason": "Named after the cover.",
            },
            {
                "i": _i(headings, "2.1"),
                "action": "drop_wrapper",
                "new_title": "",
                "reason": "A generic name holding one section.",
            },
            {
                "i": _i(headings, "2.2"),
                "action": "rename",
                "new_title": "Physical characteristics",
                "reason": "From its sub-section.",
            },
            {
                "i": _i(headings, "2.4"),
                "action": "drop_wrapper",
                "new_title": "",
                "reason": "No sections under it: refused.",
            },
            {
                "i": _i(headings, "2.7"),
                "action": "rename",
                "new_title": "Smart irrigation hub",
                "reason": "Ungrounded: refused.",
            },
            {
                "i": 9999,
                "action": "drop_wrapper",
                "new_title": "",
                "reason": "No such heading: refused.",
            },
        ],
    )
    assert rules.proposals == (
        Proposal(
            ids[_i(headings, "2")],
            "rename",
            "Greenhouse Climate Controller (GCC)",
            "Named after the cover.",
        ),
        Proposal(
            ids[_i(headings, "2.1")], "drop_wrapper", None, "A generic name holding one section."
        ),
        Proposal(
            ids[_i(headings, "2.2")], "rename", "Physical characteristics", "From its sub-section."
        ),
    )


def test_a_proposal_to_rename_after_the_cover_needs_the_cover_title(twin) -> None:
    headings = document_headings(twin)
    proposal = {
        "i": _i(headings, "2"),
        "action": "rename",
        "new_title": "Greenhouse Climate Controller (GCC)",
        "reason": "Cover.",
    }
    assert _rules(twin, proposals=[proposal]).proposals == ()


def test_a_spelling_fix_must_be_small(twin) -> None:
    headings = document_headings(twin)
    ids = {h["i"]: h["block_id"] for h in headings}
    rules = _rules(
        twin,
        spelling_fixes=[
            {"i": _i(headings, "2.10"), "fixed": "MAINTENANCE"},
            {
                "i": _i(headings, "2.7"),
                "fixed": "TIMING AND CLOCKS",
            },  # adds words: not a spelling fix
            {"i": _i(headings, "2.8"), "fixed": "CLIMATE"},  # a different word: not a spelling fix
            {"i": _i(headings, "2.9"), "fixed": "RELIABILITY"},  # unchanged: nothing to fix
        ],
    )
    assert rules.spelling_fixes == ((ids[_i(headings, "2.10")], "MAINTENANCE"),)


# --- voting -------------------------------------------------------------------------------------------------------------------------------


def _profile(**parts) -> DocumentRules:
    return DocumentRules(requirement_codes=("gen_2", "enc_1"), **parts)


def test_the_profile_is_voted_part_by_part() -> None:
    rename = Proposal("b10", "rename", "Greenhouse Climate Controller (GCC)", "Cover.")
    drop = Proposal("b11", "drop_wrapper", None, "Generic.")
    a = _profile(
        document_kind="requirements_export",
        cover_title="X (GCC)",
        proposals=(rename, drop),
        spelling_fixes=(("b20", "MAINTENANCE"),),
        title_policy="write",
    )
    b = _profile(
        document_kind="requirements_export",
        cover_title="X (GCC)",
        proposals=(rename,),
        spelling_fixes=(("b20", "MAINTENANCE"),),
        title_policy="extract",
    )
    c = _profile(
        document_kind="prose_spec",
        cover_title="Y",
        proposals=(Proposal("b10", "rename", "Something else", "Other."),),
        title_policy="write",
    )
    voted = vote_documents([a, b, c])
    assert voted.document_kind == "requirements_export"
    assert voted.cover_title == "X (GCC)"
    assert voted.proposals == (
        rename,
    )  # the drop has one vote of three; the other rename names another title
    assert voted.spelling_fixes == (("b20", "MAINTENANCE"),)
    assert voted.title_policy == "write"


def test_the_profile_vote_does_not_depend_on_the_order_the_answers_arrive_in() -> None:
    answers = [
        _profile(
            document_kind="requirements_export",
            proposals=(Proposal("b10", "rename", "Name A", "r1"),),
            title_policy="write",
        ),
        _profile(
            document_kind="requirements_export",
            proposals=(Proposal("b10", "rename", "Name A", "r2"),),
            title_policy="extract",
        ),
        _profile(
            document_kind="prose_spec",
            proposals=(Proposal("b11", "drop_wrapper", None, "r3"),),
            title_policy="write",
        ),
    ]
    assert (
        len(
            {
                FileRulebook(document=vote_documents(list(order))).hash
                for order in permutations(answers)
            }
        )
        == 1
    )


# --- the rulebook keeps the profile and the user's decisions --------------------------------------------------------------------------------


def test_the_rulebook_keeps_the_profile_and_an_older_rulebook_keeps_its_hash() -> None:
    older = FileRulebook(
        document=DocumentRules(requirement_codes=("gen_2", "enc_1"), empty_treatment="leave_out")
    )
    assert (
        "profile" not in older.canonical()["document"]
        and "decisions" not in older.canonical()["document"]
    )
    rich = FileRulebook(
        document=DocumentRules(
            requirement_codes=("gen_2", "enc_1"),
            document_kind="requirements_export",
            cover_title="Greenhouse Climate Controller (GCC)",
            proposals=(
                Proposal("b10", "rename", "Greenhouse Climate Controller (GCC)", "Cover."),
                Proposal("b11", "drop_wrapper", None, "Generic."),
            ),
            spelling_fixes=(("b20", "MAINTENANCE"),),
            title_policy="write",
            proposal_decisions=(("b10", "accept"), ("b11", "keep")),
        )
    )
    again = rulebook_from_json(rulebook_to_json(rich))
    assert again.document == rich.document and again.hash == rich.hash
    undecided = FileRulebook(
        document=DocumentRules(**{**rich.document.__dict__, "proposal_decisions": ()})
    )
    assert undecided.hash != rich.hash  # a decision changes the tree, so it changes the rulebook


