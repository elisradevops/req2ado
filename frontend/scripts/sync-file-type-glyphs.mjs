#!/usr/bin/env node
// Refreshes the Fluent 2 System Icons glyphs behind FileTypeIcon (src/components/fileTypeGlyphs.generated.ts) from Microsoft's
// fluentui-system-icons repository (MIT licence), so the file-type icons stay Fluent 2's own drawings:
//
//   node --use-system-ca scripts/sync-file-type-glyphs.mjs
//
// Run by hand, never by the build: the app never calls GitHub or a CDN. Review the diff before committing.
import { writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const RAW = 'https://raw.githubusercontent.com/microsoft/fluentui-system-icons/main/assets';
// Glyph key -> the Fluent asset folder and file stem. Each is fetched in the filled style at 20 px (rows) and 32 px (tiles), when
// Microsoft draws that size; a glyph drawn only at 20 px is scaled for tiles.
const GLYPHS = {
  document: ['Document', 'document'],
  documentText: ['Document Text', 'document_text'],
  documentPdf: ['Document PDF', 'document_pdf'],
  documentData: ['Document Data', 'document_data'],
  documentOnePage: ['Document One Page', 'document_one_page'],
  documentHeader: ['Document Header', 'document_header'],
  slideText: ['Slide Text', 'slide_text'],
  image: ['Image', 'image'],
  archive: ['Archive', 'archive'],
  code: ['Code', 'code'],
  mail: ['Mail', 'mail'],
  video: ['Video', 'video'],
  musicNote: ['Music Note 2', 'music_note_2'],
  folder: ['Folder', 'folder'],
};

async function glyph(folder, stem, size) {
  const response = await fetch(`${RAW}/${encodeURIComponent(folder)}/SVG/ic_fluent_${stem}_${size}_filled.svg`);
  if (response.status === 404) return null;
  if (!response.ok) throw new Error(`${folder} ${size}: HTTP ${response.status}`);
  const svg = await response.text();
  if (/<script|\son[a-z]+=|href=/i.test(svg)) throw new Error(`${folder} ${size}: holds a script or a link, refusing it`);
  const paths = [...svg.matchAll(/<path\b[^>]*\sd="([^"]+)"[^>]*>/g)].map((m) => m[1]);
  if (paths.length === 0) throw new Error(`${folder} ${size}: no path`);
  return { size, paths };
}

const out = {};
for (const [key, [folder, stem]] of Object.entries(GLYPHS)) {
  const drawings = (await Promise.all([20, 32].map((size) => glyph(folder, stem, size)))).filter(Boolean);
  if (drawings.length === 0) throw new Error(`${folder}: no 20 px or 32 px drawing`);
  out[key] = Object.fromEntries(drawings.map((d) => [d.size, d.paths]));
}

await writeFile(
  join(ROOT, 'src/components/fileTypeGlyphs.generated.ts'),
  '// Generated by scripts/sync-file-type-glyphs.mjs from microsoft/fluentui-system-icons (MIT licence), filled style. Do not edit by hand.\n' +
    '/** Glyph -> its drawings by size in px (20 for rows, 32 for tiles) -> the SVG path data, drawn in a square viewBox of that size. */\n' +
    `export const FILE_TYPE_GLYPHS = ${JSON.stringify(out, null, 2)} as const satisfies Record<string, Partial<Record<20 | 32, readonly string[]>>>;\n\n` +
    'export type FileTypeGlyph = keyof typeof FILE_TYPE_GLYPHS;\n',
);
console.log(Object.entries(out).map(([k, v]) => `${k} ${Object.keys(v).join('/')}`).join(', '));
